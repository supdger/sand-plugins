#!/usr/bin/env python3
"""Check that staged SandAI payload matches its recorded delivery digest.

`sand-ai/plugin/` is generated by scripts/deliver-sand-ai.sh from the SandAI
development source of truth; it is never hand-edited here. This gate reads the
actual Git index, never a dirty worktree, and refuses a commit whose staged
payload disagrees with sand-ai/.delivery-source.json.
"""

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path, PurePosixPath

RECORD_PATH = "sand-ai/.delivery-source.json"
PAYLOAD_PREFIX = "sand-ai/plugin/"
MIRROR_ROOT = "sand-ai/plugin/sand-ai"
HINT = "sand-ai/plugin/ is delivered content: run scripts/deliver-sand-ai.sh --apply and stage the result"


def git(*arguments):
    return subprocess.run(["git", *arguments], check=True, stdout=subprocess.PIPE).stdout


def digest(entries):
    """Canonical digest: sha256 over sorted `<sha256>  <relative path>` lines."""
    lines = []
    for relative, content in sorted(entries):
        lines.append(f"{hashlib.sha256(content).hexdigest()}  {relative}\n")
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest(), len(lines)


def tree_entries(root: Path):
    for path in root.rglob("*"):
        if path.is_file() and not path.is_symlink():
            yield PurePosixPath(path.relative_to(root)).as_posix(), path.read_bytes()


def index_entries(prefix):
    """Blob contents staged under `prefix`, keyed by path relative to it."""
    listing = git("ls-files", "-s", "-z", "--", prefix).decode("utf-8").split("\0")
    staged = []
    for record in listing:
        if not record:
            continue
        metadata, path = record.split("\t", 1)
        _mode, blob, stage = metadata.split()
        if stage != "0":
            raise ValueError(f"{path}: unmerged index entry; resolve the conflict first")
        staged.append((path, blob))
    if not staged:
        return []
    request = "".join(blob + "\n" for _path, blob in staged).encode("utf-8")
    batch = subprocess.run(["git", "cat-file", "--batch"], input=request,
                           check=True, stdout=subprocess.PIPE).stdout
    entries = []
    offset = 0
    for path, _blob in staged:
        header_end = batch.index(b"\n", offset)
        size = int(batch[offset:header_end].split()[2])
        start = header_end + 1
        entries.append((PurePosixPath(path).relative_to(prefix).as_posix(), batch[start:start + size]))
        offset = start + size + 1
    return entries


def record_from_index():
    if RECORD_PATH not in set(git("ls-files", "-z").decode("utf-8").split("\0")):
        raise ValueError(f"missing delivery record {RECORD_PATH}: {HINT}")
    record = json.loads(git("show", ":" + RECORD_PATH).decode("utf-8"))
    if record.get("format") != 1:
        raise ValueError(f"{RECORD_PATH}: unsupported record format {record.get('format')!r}")
    if record.get("target_subdir") != MIRROR_ROOT:
        raise ValueError(f"{RECORD_PATH}: record targets {record.get('target_subdir')!r}, expected {MIRROR_ROOT}")
    for field in ("source_repo", "source_commit", "source_subdir", "content_sha256", "file_count"):
        if not record.get(field):
            raise ValueError(f"{RECORD_PATH}: missing field {field}")
    return record


def check_index():
    changed = git("diff", "--cached", "--no-renames", "--name-only",
                  "--diff-filter=ACMRD", "-z").decode("utf-8").split("\0")
    touched = [name for name in changed if name and (name.startswith(PAYLOAD_PREFIX) or name == RECORD_PATH)]
    if not touched:
        print("SandAI delivery check skipped (no staged delivery payload).")
        return 0
    stray = sorted(name for name in git("ls-files", "-z", "--", PAYLOAD_PREFIX).decode("utf-8").split("\0")
                   if name and not name.startswith(MIRROR_ROOT + "/"))
    if stray:
        raise ValueError(f"{PAYLOAD_PREFIX} holds non-delivered paths: {', '.join(stray)}")
    record = record_from_index()
    actual, count = digest(index_entries(MIRROR_ROOT))
    if actual != record["content_sha256"] or count != record["file_count"]:
        raise ValueError(
            f"staged {MIRROR_ROOT} ({count} files, {actual}) does not match "
            f"{RECORD_PATH} ({record['file_count']} files, {record['content_sha256']}): {HINT}"
        )
    print(f"[PASS] SandAI delivery: {count} files at {record['source_commit']}")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--digest-tree", type=Path,
                        help="print `<sha256> <file count>` for a delivered tree and exit")
    arguments = parser.parse_args()
    if arguments.digest_tree is not None:
        root = arguments.digest_tree.resolve()
        if not root.is_dir():
            raise ValueError(f"{root} is not a directory")
        content_sha256, count = digest(tree_entries(root))
        print(f"{content_sha256} {count}")
        return 0
    return check_index()


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, UnicodeError, json.JSONDecodeError, subprocess.CalledProcessError) as error:
        print(f"[FAIL] {error}", file=sys.stderr)
        raise SystemExit(1)
